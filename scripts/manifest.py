#!/usr/bin/env python3
"""The authority manifest: derived by the compiler, embedded by the build, gated against a ceiling (cancho docs/agent-toolbox.md D12).

For every [[bin]] in cancho.toml:

1. pass 1: `cancho authority <sources> <installed deps> --std --output json`;
2. write manifests/<tool>.authority.json (the committed record) and generated/<tool>/built.cho, which holds the authority, the tool's schema
   (schemas/flow.v1.json) and the compiler pin as string literals;
3. pass 2: derive again with the new generated file and require the same report (the fixed point: a string constant adds no label);
4. require every derived label to be within the program's ceiling in tools.toml, `bounded` to be true and no foreign symbol, `exec` and
   `clock` only for `flow` (and `clock` only with a stated exception), and `flow-records` to hold none of exec, clock, a write, a pipe or a
   child signal.

    python3 scripts/manifest.py            # regenerate, then check
    python3 scripts/manifest.py --check    # change nothing; exit 1 on drift

`--check` also compares what each built binary prints (`build/<tool> introspect`) with the fresh derivation when the binary exists. The
compiler is $CANCHO, or `cancho` on PATH; `cancho install` must have run.
"""

import json
import os
import pathlib
import subprocess
import sys
import tomllib

ROOT = pathlib.Path(__file__).resolve().parent.parent
FORBIDDEN = {"ffi", "net_out", "net_in"}
READ_ONLY = {"flow-records"}
NEVER_READ_ONLY = {"exec", "clock", "file_write", "dir_write", "pipe_read", "pipe_write", "child_signal", "poll", "io_read"}


def compiler():
    return os.environ.get("CANCHO", "cancho")


def sources(entry, tree=None):
    files = []
    for s in entry["sources"]:
        p = (tree or ROOT) / s
        files.extend(sorted(str(x) for x in p.glob("*.cho")) if p.is_dir() else [str(p)])
    return files


def installed():
    deps = ROOT / "build" / "deps"
    files = sorted(str(x) for x in deps.glob("*.cho")) if deps.is_dir() else []
    if not files:
        sys.exit("manifest: build/deps is empty; run `cancho install` first")
    return files


def derive(files):
    out = subprocess.run([compiler(), "authority", *files, "--std", "--output", "json"], capture_output=True, text=True)
    if out.returncode != 0:
        sys.exit("cancho authority failed:\n" + out.stdout + out.stderr)
    return json.loads(out.stdout)


def compact(value):
    return json.dumps(value, separators=(",", ":"), ensure_ascii=True)


def literal(text):
    """A cancho string literal: six escapes, no others, one line."""
    out = []
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\r":
            out.append("\\r")
        elif ord(ch) < 32:
            sys.exit("a control character cannot be written in a cancho literal")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def generated(authority, schema, pin):
    return """edition 5;

module toolbox.built;

// Generated by scripts/manifest.py -- do not edit. The compiler's authority report for this program, its JSON Schema, and the compiler it
// was written for, as `introspect` prints them (cancho docs/agent-toolbox.md D12). Each program has its own copy of this module.

pub fn authority() -> [] &static [byte] {
    return %s;
}

pub fn schema() -> [] &static [byte] {
    return %s;
}

pub fn compiler() -> [] &static [byte] {
    return %s;
}
""" % (literal(compact(authority)), literal(compact(schema)), literal(pin))


def label_text(label):
    if label["argument"] is None:
        return label["name"]
    return '%s("%s")' % (label["name"], label["argument"])


def gate(tool, authority, ceilings):
    problems = []
    ceiling = ceilings.get(tool)
    if ceiling is None:
        return ["%s: no ceiling in tools.toml" % tool]
    allowed = set(ceiling.get("allow", []))
    exceptions = ceiling.get("exceptions", {})
    if not authority.get("bounded", False):
        problems.append("%s: bounded is false" % tool)
    if authority.get("foreign_symbols"):
        problems.append("%s: foreign symbols %s" % (tool, authority["foreign_symbols"]))
    names = set()
    for label in authority["labels"]:
        text = label_text(label)
        names.add(label["name"])
        if label["name"] in FORBIDDEN:
            problems.append("%s: %s is forbidden to every program" % (tool, text))
        if label["name"] == "clock" and not exceptions.get("clock"):
            problems.append("%s: clock needs an exception with a reason in tools.toml" % tool)
        if label["name"] == "exec" and tool in READ_ONLY:
            problems.append("%s: exec is forbidden to a read-only program" % tool)
        if text not in allowed:
            problems.append("%s: %s is not within the ceiling in tools.toml" % (tool, text))
    if tool in READ_ONLY:
        for bad in sorted(names & NEVER_READ_ONLY):
            problems.append("%s: %s is forbidden to a read-only program" % (tool, bad))
    if exceptions.get("clock") and "clock" not in names:
        problems.append("%s: tools.toml excuses clock and the program does not use it (a stale exception)" % tool)
    return problems


def introspected(tool):
    binary = ROOT / "build" / tool
    if not binary.exists():
        return None
    out = subprocess.run([str(binary), "introspect"], capture_output=True, text=True)
    if out.returncode != 0:
        return "introspect exited %d" % out.returncode
    return json.loads(out.stdout)["authority"]


def main():
    argv = sys.argv[1:]
    check = "--check" in argv
    proj = tomllib.loads((ROOT / "cancho.toml").read_text())
    pin = proj["package"]["cancho"]
    ceilings = tomllib.loads((ROOT / "tools.toml").read_text())
    bins = [b for b in proj.get("bin", []) if b["name"] in ceilings]
    problems = []
    if len(bins) > ceilings.get("max_tools", 2):
        problems.append("%d programs; tools.toml allows %d" % (len(bins), ceilings["max_tools"]))
    deps = installed()
    schema = json.loads((ROOT / "schemas" / "flow.v1.json").read_text())
    for entry in bins:
        tool = entry["name"]
        files = sources(entry) + deps
        first = derive(files)
        record = ROOT / "manifests" / ("%s.authority.json" % tool)
        built = ROOT / "generated" / tool / "built.cho"
        record_text = json.dumps(first, indent=2) + "\n"
        built_text = generated(first, schema, pin)
        if check:
            if not record.exists() or record.read_text() != record_text:
                problems.append("%s: %s is not the compiler's report" % (tool, record.relative_to(ROOT)))
            if not built.exists() or built.read_text() != built_text:
                problems.append("%s: %s is stale" % (tool, built.relative_to(ROOT)))
            embedded = introspected(tool)
            if embedded is not None and embedded != first:
                problems.append("%s: build/%s introspect prints an authority that is not the compiler's (a stale build?)" % (tool, tool))
        else:
            record.parent.mkdir(exist_ok=True)
            record.write_text(record_text)
            built.parent.mkdir(parents=True, exist_ok=True)
            built.write_text(built_text)
            if derive(files) != first:
                problems.append("%s: no fixed point -- embedding the manifest changed the authority" % tool)
        problems.extend(gate(tool, first, ceilings))
        print("%-13s %s" % (tool, ", ".join(label_text(l) for l in first["labels"])))
    for p in problems:
        print("FAIL " + p)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
